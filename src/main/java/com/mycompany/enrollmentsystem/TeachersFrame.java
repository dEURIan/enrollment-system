        public void showRecords(){
        DefaultTableModel tblmodel = (DefaultTableModel) teacherTable.getModel();
        tblmodel.setRowCount(0);
        EnrollmentSystem b = new EnrollmentSystem();
        b.DBConnect();
        
        String searchText = search.getText();
        if (searchText.equals("Search")) searchText = ""; // HOPEFULLY shows tables after saving
    
        
        try{
            String query = "select * from teachers where concat_ws(tid, tname, tdept, tcontact) like '%" + searchText + "%'";
            b.rs = b.st.executeQuery(query);
            System.out.println("Success with sql!");  
            
            while (b.rs.next()){
                String i = b.rs.getString("tid");
                String c = b.rs.getString("tname");
                String d = b.rs.getString("tdept");
                String t = b.rs.getString("tcontact");
                String[] items = {i,c,d,t};
                tblmodel.addRow(items); //array
            }
        }catch (Exception ex){
            System.out.print("not Success with sql!");
        }
    }
    
