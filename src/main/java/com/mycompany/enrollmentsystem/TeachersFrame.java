    private void teacherTableMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_teacherTableMouseClicked
        int[] selectRow = teacherTable.getSelectedRows();
        if (selectRow.length > 0) {
            String teachid = (String) teacherTable.getValueAt(selectRow[0], 0);
            tid.setText(teachid);

            // Lock ID so it cannot be modified
            tid.setEditable(false);

            String teachname = (String) teacherTable.getValueAt(selectRow[0], 1);
            tname.setText(teachname);
            String teachdept = (String) teacherTable.getValueAt(selectRow[0], 2);
            tdept.setText(teachdept);
            String teachcontact = (String) teacherTable.getValueAt(selectRow[0], 3);
            tcontact.setText(teachcontact);
        }
    }//GEN-LAST:event_teacherTableMouseClicked

    private void SaveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_SaveActionPerformed
       int id = Integer.parseInt(tid.getText().trim());
        EnrollmentSystem db = new EnrollmentSystem();

        if (db.isIdExists("teachers", "tid", id)) {
            messagebox("Teacher ID already exists! Cannot create duplicate row.", "Duplicate ID");
            return;
        }
        
        Teacher c = new Teacher();
        c.newteacher(Integer.parseInt(tid.getText()), tname.getText(),tdept.getText(),tcontact.getText());
        showRecords();        
    }//GEN-LAST:event_SaveActionPerformed

    private void DeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_DeleteActionPerformed
        if (tid.getText().trim().isEmpty()) {
            messagebox("select a student to delete first", "Delete");
            return;
        }
        
        Teacher c = new Teacher();
        c.deleteteacher(Integer.parseInt(tid.getText()));
        showRecords();
        clearFields(); 
    }//GEN-LAST:event_DeleteActionPerformed

    private void EditActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_EditActionPerformed
        if (tid.getText().trim().isEmpty()) {
            messagebox("select a student to edit first", "Edit");
            return;
        }
        Teacher c = new Teacher();
        c.updateteacher(Integer.parseInt(tid.getText()), tname.getText(), tdept.getText(), tcontact.getText());
        showRecords();
        clearFields();      
    }//GEN-LAST:event_EditActionPerformed

